/**
 * Generates default College Campus clues based on official campus landmarks & riddles.
 * Organizers can select any number of clues from 1 to 10.
 */
export const generateCollegeCampusClues = (
  eventId: string,
  count: number = 8,
  campusName: string = 'Central Campus'
): Clue[] => {
  const safeCount = Math.max(1, Math.min(10, count || 8));
  const timestamp = Date.now();
  return COLLEGE_CAMPUS_DEFAULT_CLUES.slice(0, safeCount).map((item, idx) => ({
    id: `clue-college-${idx + 1}-${timestamp}`,
    eventId,
    title: item.title,
    riddle: item.riddle,
    locationHint: `${item.answerPlace} (${campusName})`,
    solution: item.answerKey,
    answerKey: item.answerKey,
    type: 'qr_code' as const,
    points: item.points,
    order: idx + 1,
    hint1: item.hint1,
    hint2: item.hint2,
    qrCodeValue: `CQ_CHECKPOINT:${eventId}:clue-${idx + 1}:${item.answerKey}`,
    placementNote: item.placeInstruction,
  }));
};

